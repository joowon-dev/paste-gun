    /// 렌더러가 정해 준 단축키로 갈아 끼운다.
    private func setHotkeys(_ list: [[String: Any]]) {
        let bindings: [KeyTap.Binding] = list.compactMap { item in
            guard let id = (item["id"] as? NSNumber)?.uint32Value,
                  let key = (item["key"] as? NSNumber)?.int64Value else { return nil }
            var flags: CGEventFlags = []
            if item["meta"] as? Bool == true { flags.insert(.maskCommand) }
            if item["ctrl"] as? Bool == true { flags.insert(.maskControl) }
            if item["alt"] as? Bool == true { flags.insert(.maskAlternate) }
            if item["shift"] as? Bool == true { flags.insert(.maskShift) }
            return KeyTap.Binding(id: id, key: key, flags: flags)
        }
        keyTap.set(bindings)
        debugLog("단축키 \(bindings.count)개, 탭 \(keyTap.running)")
    }

    fileprivate func hotKeyPressed(_ id: UInt32) {
        debugLog("hotkey \(id)")
        if id > HotKey.snipeBase {
            call("__gunSnipe", Int(id - HotKey.snipeBase))
            return
        }
        switch HotKey(rawValue: id) {
        case .trigger: call("__gunTrigger")
        case .nextGun: call("__gunNextGun")
        case .nextMagazine: call("__gunNextMagazine")
        case .panel: togglePanel()
        case nil: break
        }
    }

    /// 단축키는 사람 손으로만 눌린다. 디버그 때만 대신 누른다.
    ///   notifyutil -p pastegun.<id>        그 동작을 곧장 부른다 (탭을 안 거친다)
    ///   notifyutil -p pastegun.press.<id>  그 동작의 **진짜 키**를 표시 없이 보낸다 (탭을 거친다)
    ///   notifyutil -p pastegun.cmd.down / .up   ⌘ 를 누른 채인 것처럼 만든다
    private func registerDebugTriggers() {
        let ids = (0...3).map { UInt32($0) } + (1...9).map { HotKey.snipeBase + UInt32($0) }
        var token: Int32 = 0
        for id in ids {
            notify_register_dispatch("pastegun.\(id)", &token, .main) { [weak self] _ in
                self?.hotKeyPressed(id)
            }
            notify_register_dispatch("pastegun.press.\(id)", &token, .main) { [weak self] _ in
                guard let binding = self?.keyTap.binding(id) else { return }
                let source = CGEventSource(stateID: .combinedSessionState)
                for down in [true, false] {
                    let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(binding.key), keyDown: down)
                    event?.flags = binding.flags
                    event?.post(tap: .cghidEventTap)
                }
            }
        }
        // notifyutil -p pastegun.eval — PASTEGUN_EVAL 이 가리키는 파일의 JS 를 렌더러에서 돌린다.
        notify_register_dispatch("pastegun.eval", &token, .main) { [weak self] _ in
            guard let path = ProcessInfo.processInfo.environment["PASTEGUN_EVAL"],
                  let code = try? String(contentsOfFile: path, encoding: .utf8) else { return }
            self?.webView.evaluateJavaScript(code) { result, error in
                debugLog("eval → \(result.map { "\($0)" } ?? "-") \(error.map { "\($0)" } ?? "")")
            }
        }
        for (name, down) in [("down", true), ("up", false)] {
            notify_register_dispatch("pastegun.cmd.\(name)", &token, .main) { _ in
                let event = CGEvent(keyboardEventSource: CGEventSource(stateID: .combinedSessionState),
                                    virtualKey: CGKeyCode(kVK_Command), keyDown: down)
                event?.flags = down ? .maskCommand : []
                event?.setIntegerValueField(.eventSourceUserData, value: KeyTap.mark)
                event?.post(tap: .cghidEventTap)
                debugLog("⌘ \(name) → \(CGEventSource.flagsState(.combinedSessionState).contains(.maskCommand))")
            }
        }
    }

    // MARK: 무기고

    @objc private func togglePanel() { setPanel(!panelOpen) }

    private func setPanel(_ open: Bool) {
        guard open != panelOpen else { return }
        if open && hudHidden { setHidden(false) }
        panelOpen = open
        call("__gunPanel", open)

        cursorTimer?.invalidate()
        cursorTimer = nil
        if open {
            // 커서가 무기고 위인지는 물어봐야 안다 — 창이 마우스를 안 받는 동안에는 이벤트가 안 온다.
            cursorTimer = Timer.scheduledTimer(withTimeInterval: 1.0 / 30.0, repeats: true) { [weak self] _ in
                self?.updateCursorOverPanel()
            }
        } else {
            panelRect = nil
            cursorOverPanel = false
            releaseKeyboard()
        }
        updateMousePass()
        refreshMenu()
    }

    /// **창이 마우스를 받는 것은 커서가 무기고 네모 위에 있을 때뿐이다.** 이 창은 화면
    /// 전체라, 무기고가 열렸다고 통째로 받으면 다른 창을 아예 못 누른다.
    private func updateCursorOverPanel() {
        var inside = false
        if panelOpen, let rect = panelRect {
            let frame = window.frame
            let cursor = NSEvent.mouseLocation
            // 화면 좌표(왼쪽 아래 기준) → 창 안 좌표(왼쪽 위 기준)
            inside = NSPointInRect(NSPoint(x: cursor.x - frame.minX, y: frame.maxY - cursor.y), rect)
        }
        guard inside != cursorOverPanel else { return }
        cursorOverPanel = inside
        updateMousePass()
    }

    private func updateMousePass() {
        let wantPass = !cursorOverPanel
        guard wantPass != passingThrough else { return }
        passingThrough = wantPass
        window.ignoresMouseEvents = wantPass
        debugLog("pass \(wantPass)")
    }

    /// 글자 칸을 눌렀다. 이제서야 키보드를 가져온다.
    private func grabKeyboard() {
        guard !holdingKeyboard else { return }
        holdingKeyboard = true
        keyTap.setPaused(true)
        // 돌려줄 곳을 적어 둔다. deactivate() 만으로는 쓰던 앱이 앞으로 안 돌아오는 일이 있다.
        let front = NSWorkspace.shared.frontmostApplication
        if front?.processIdentifier != ProcessInfo.processInfo.processIdentifier { previousApp = front }
        NSApp.activate(ignoringOtherApps: true)
        window.makeKeyAndOrderFront(nil)
    }

    /// 글자 칸에서 손을 뗐거나 무기고를 닫았다. 쓰던 앱으로 돌려준다.
    private func releaseKeyboard() {
        guard holdingKeyboard else { return }
        holdingKeyboard = false
        keyTap.setPaused(false)
        NSApp.deactivate()
        previousApp?.activate()
        previousApp = nil
    }

