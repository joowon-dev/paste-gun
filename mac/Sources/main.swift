/**
 전역 단축키. **키보드 이벤트 탭**으로 잡는다 — 맞는 키는 삼키고 나머지는 그대로 흘린다.

 다른 앱들은 `RegisterEventHotKey` 를 쓰지만 이 앱은 못 쓴다. 기본 방아쇠가 **⌘V 그 자체**라서다:
   · 우리가 붙여넣으려고 보낸 ⌘V 를 우리 핫키가 다시 잡으면 안 된다. 탭은 이벤트에 붙인
     표시(`mark`)로 「우리가 보낸 것」을 알아보고 흘려보낸다. 핫키는 그걸 구별할 길이 없다.
   · 쏠 것이 없을 때는 진짜 붙여넣기를 흘려보내야 한다. 그것도 표시를 붙인 ⌘V 다.
 「삼킨다」는 성질은 핫키와 같다. 대가는 **손쉬운 사용 권한이 있어야 단축키가 살아난다**는
 것인데, 이 앱은 그 권한 없이는 어차피 한 발도 못 쏜다.

 탭은 자기 스레드에서 돈다. 메인 스레드가 잠깐 바쁘다고 온 시스템의 타자가 버벅이면 안 된다.
 */
final class KeyTap {
    /// 우리가 보낸 키에 붙이는 표시('PGUN').
    static let mark: Int64 = 0x5047_554E
    private static let modifierMask: CGEventFlags = [.maskCommand, .maskControl, .maskAlternate, .maskShift]

    struct Binding { let id: UInt32; let key: Int64; let flags: CGEventFlags }

    private let lock = NSLock()
    private var bindings: [Binding] = []
    private var paused = false
    private var port: CFMachPort?
    private let onPress: (UInt32) -> Void

    init(onPress: @escaping (UInt32) -> Void) { self.onPress = onPress }

    var running: Bool { port != nil }

    func set(_ list: [Binding]) { lock.lock(); bindings = list; lock.unlock() }
    /// 무기고에서 글자를 치는 동안에는 아무것도 안 잡는다 — 거기서도 ⌘V 는 붙여넣기여야 한다.
    func setPaused(_ on: Bool) { lock.lock(); paused = on; lock.unlock() }
    func binding(_ id: UInt32) -> Binding? {
        lock.lock(); defer { lock.unlock() }
        return bindings.first { $0.id == id }
    }

    /// 탭을 건다. 손쉬운 사용 권한이 없으면 실패한다 — 권한이 생긴 뒤 다시 부른다.
    @discardableResult
    func start() -> Bool {
        if port != nil { return true }
        let mask = CGEventMask(1 << CGEventType.keyDown.rawValue)
        guard let port = CGEvent.tapCreate(
            tap: .cgSessionEventTap, place: .headInsertEventTap, options: .defaultTap,
            eventsOfInterest: mask,
            callback: { _, type, event, refcon in
                let tap = Unmanaged<KeyTap>.fromOpaque(refcon!).takeUnretainedValue()
                return tap.handle(type, event) ? nil : Unmanaged.passUnretained(event)
            },
            userInfo: Unmanaged.passUnretained(self).toOpaque()) else { return false }
        self.port = port
        let thread = Thread {
            let source = CFMachPortCreateRunLoopSource(nil, port, 0)
            CFRunLoopAddSource(CFRunLoopGetCurrent(), source, .commonModes)
            CGEvent.tapEnable(tap: port, enable: true)
            CFRunLoopRun()
        }
        thread.name = "paste-gun.keytap"
        thread.qualityOfService = .userInteractive
        thread.start()
        return true
    }

    /// 권한을 거둬 갔다. 살아 있는 탭을 그대로 두면 키보드가 통째로 먹통이 될 수 있다.
    func stop() {
        guard let port else { return }
        CGEvent.tapEnable(tap: port, enable: false)
        CFMachPortInvalidate(port)
        self.port = nil
    }

    /// 삼킬 것이면 true.
    private func handle(_ type: CGEventType, _ event: CGEvent) -> Bool {
        if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
            // 시스템이 「느리다」며 탭을 꺼 버리는 일이 있다. 다시 켠다 — 안 켜면 단축키가 조용히 죽는다.
            if let port { CGEvent.tapEnable(tap: port, enable: true) }
            return false
        }
        guard type == .keyDown, event.getIntegerValueField(.eventSourceUserData) != Self.mark else { return false }
        let key = event.getIntegerValueField(.keyboardEventKeycode)
        let flags = event.flags.intersection(Self.modifierMask)
        lock.lock()
        let match = paused ? nil : bindings.first { $0.key == key && $0.flags == flags }
        lock.unlock()
        guard let match else { return false }
        // 누르고 있어서 되풀이되는 것은 삼키기만 한다. 한 번 누른 것은 한 번이다.
        if event.getIntegerValueField(.keyboardEventAutorepeat) == 0 {
            let id = match.id
            DispatchQueue.main.async { self.onPress(id) }
        }
        return true
    }
}

