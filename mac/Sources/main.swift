    private func savedStateLiteral() -> String {
        guard let text = UserDefaults.standard.string(forKey: stateKey),
              let data = text.data(using: .utf8),
              let value = try? JSONSerialization.jsonObject(with: data) else { return "null" }
        return jsLiteral(value) // 한 번 읽었다 다시 쓴다. 깨진 글이 스크립트에 섞이지 않게.
    }

    private func bridgeScript() -> String {
        return """
        (() => {
          const post = (m) => window.webkit.messageHandlers.gun.postMessage(m)
          const hook = (name) => (handler) => { window[name] = handler }
          window.__gunTrustedNow = \(trusted || dryRun)
          window.sneaky = {
            platform: 'mac',
            getState: () => Promise.resolve(\(savedStateLiteral())),
            saveState: (s) => post({ type: 'state', json: JSON.stringify(s) }),
            setHotkeys: (list, hint, panelLabel) => post({ type: 'hotkeys', list, hint: String(hint || ''), panelLabel: String(panelLabel || '') }),
            pass: () => post({ type: 'pass' }),
            fire: (shot) => post({ type: 'fire', text: String(shot.text), after: shot.after || null, how: shot.how || 'paste', lead: Number(shot.lead) || 0 }),
            setStatus: (text) => post({ type: 'status', text: String(text) }),
            setPanelRect: (r) => post({ type: 'panelRect', rect: r ? { x: r.x, y: r.y, w: r.w, h: r.h } : null }),
            closePanel: () => post({ type: 'closePanel' }),
            grabKeyboard: () => post({ type: 'grabKeyboard' }),
            releaseKeyboard: () => post({ type: 'releaseKeyboard' }),
            onTrigger: hook('__gunTrigger'),
            onSnipe: hook('__gunSnipe'),
            onNextGun: hook('__gunNextGun'),
            onNextMagazine: hook('__gunNextMagazine'),
            onCopied: hook('__gunCopied'),
            onCopiedOther: hook('__gunCopiedOther'),
            onPanel: hook('__gunPanel'),
            onHidden: hook('__gunHidden'),
            onShotAt: hook('__gunShotAt'),
            onTrusted: (handler) => { window.__gunTrusted = handler; handler(window.__gunTrustedNow) },
          }
          // 웹뷰는 콘솔이 안 보인다. 오류만이라도 셸의 stderr 로 흘려보낸다.
          window.addEventListener('error', (e) => post({ type: 'log', text: `${e.message} (${e.filename}:${e.lineno})` }))
          window.addEventListener('unhandledrejection', (e) => post({ type: 'log', text: `reject ${e.reason}` }))
          console.error = (...args) => post({ type: 'log', text: args.join(' ') })
        })()
        """
    }

    private func call(_ name: String, _ arguments: Any...) {
        let list = arguments.map(jsLiteral).joined(separator: ", ")
        webView.evaluateJavaScript("window.\(name) && window.\(name)(\(list))")
    }

    // MARK: 클립보드 — 복사한 것이 총알이 된다

    /// 클립보드는 바뀌었다고 알려 주지 않는다. 바뀐 횟수를 물어보는 수밖에 없다.
    private func pollClipboard() {
        let board = NSPasteboard.general
        let change = board.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard change != ownChange else { return }

        let types = board.types ?? []
        guard !types.contains(where: secretTypes.contains),
              let text = board.string(forType: .string) else {
            // 그림·파일·비밀번호. 총알이 아니다 — 렌더러에 알려야 ⌘V 가 그것을 그대로 붙여넣는다.
            debugLog("복사 (글이 아님)")
            call("__gunCopiedOther")
            return
        }
        debugLog("복사 \(text.count)자")
        call("__gunCopied", text)
    }

    // MARK: 발사

    private func pollTrust() {
        let now = AXIsProcessTrusted()
        guard now != trusted else { return }
        trusted = now
        debugLog("손쉬운 사용 \(now)")
        // 단축키 탭은 이 권한이 있어야 걸린다. 생기면 걸고, 거둬 가면 푼다.
        if now { keyTap.start() } else { keyTap.stop() }
        webView.evaluateJavaScript("window.__gunTrustedNow = \(now); window.__gunTrusted && window.__gunTrusted(\(now))")
        refreshMenu()
    }

    /// 시스템의 권한 안내 창을 띄운다. 한 번 거절한 뒤에는 아무것도 안 뜨므로 메뉴에도 길을 둔다.
    private func askForTrust() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    @objc private func openTrustSettings() {
