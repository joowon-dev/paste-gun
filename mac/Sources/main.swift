    /// 클립보드를 덮어쓰면 같은 총알이 두 번 찍힌다.
    ///
    /// **넣는 길이 둘이다.** 한 글자씩 쏘는 총은 글자를 직접 쳐 넣고(`typed`), 저격총은
    /// 통째로 붙여넣는다. 초당 30발을 붙여넣기로 쏘면 위의 그 클립보드 경주에서 진다.
    /// 다만 **줄바꿈과 탭은 쳐 넣지 않고 붙여넣는다** — 쳐 넣은 Return 은 메신저에서
    /// 「보내기」다. 붙여넣은 줄바꿈은 어디서나 그냥 줄바꿈이다.
    private func fire(text: String, after: String?, typed: Bool, lead: Double) {
        // 화면에서 글자가 총구를 떠나 과녁에 닿기까지(ms). 그만큼 기다렸다 넣으면 꽂히는 순간에 찍힌다.
        let flight = useconds_t(max(0, min(lead, 400)) * 1000)
        let typed = typed && !text.contains { $0.isNewline || $0 == "\t" }
        if dryRun {
            debugLog("발사(연습) \(jsLiteral(text)) after=\(after ?? "-")")
            showShot(at: Self.caretPoint(), text: text)
            return
        }
        guard AXIsProcessTrusted() else {
            // 권한 없이 보낸 키는 에러도 없이 사라진다. 클립보드만 바뀌고 아무것도 안 찍히는
            // 상태를 만들지 않는다.
            debugLog("권한 없음 — 안 쏨")
            pollTrust()
            return
        }

        fireQueue.async { [weak self] in
            guard let self else { return }
            self.waitForModifiersUp()
            // **붙여넣기 전에 묻는다.** 붙여넣고 나면 커서는 이미 글 끝으로 가 있다.
            let caret = Self.caretPoint()

            if typed {
                DispatchQueue.main.sync { self.showShot(at: caret, text: text) }
                usleep(flight)
                Self.type(text)
                usleep(afterType)
            } else {
                DispatchQueue.main.sync {
                    self.showShot(at: caret, text: text)
                    let board = NSPasteboard.general
                    board.clearContents()
                    board.setString(text, forType: .string)
                    self.ownChange = board.changeCount
                }
                usleep(max(beforePaste, flight))
                Self.tap(key: CGKeyCode(kVK_ANSI_V), flags: .maskCommand)
                usleep(afterPaste)
            }

            if let after, let key = after == "tab" ? kVK_Tab : after == "enter" ? kVK_Return : nil {
                usleep(typed ? afterType : beforeAfterKey)
                Self.tap(key: CGKeyCode(key), flags: [])
            }
            debugLog("발사 \(typed ? "타자" : "붙여넣기") \(text.count)자 after=\(after ?? "-")"
                     + (CGEventSource.flagsState(.combinedSessionState).contains(.maskCommand) ? " (⌘ 눌린 채)" : ""))
        }
    }

    /// 총이 쏠 일이 아니다. 삼켰던 붙여넣기 키를 **원래대로** 눌러 준다. 클립보드는 안 건드린다.
    private func passPaste() {
        guard AXIsProcessTrusted(), !dryRun else { return }
        fireQueue.async {
            Self.tap(key: CGKeyCode(kVK_ANSI_V), flags: .maskCommand)
            debugLog("흘려보냄 ⌘V")
        }
    }

    /**
     지금 글자가 들어갈 자리(글자 커서)의 화면 좌표. 왼쪽 위가 원점이다. 모르면 nil.

     손쉬운 사용 API 로 「지금 포커스가 있는 것 → 선택 범위 → 그 범위의 네모」를 묻는다.
     발사에 이미 쓰는 권한이라 새로 받을 것이 없다. **모든 앱이 답해 주지는 않는다** —
     크롬·일렉트론 계열은 손쉬운 사용 트리를 평소에 꺼 두고, 터미널류는 글자 커서를 안
     알려 준다. 그럴 때는 nil 이고, 부르는 쪽이 마우스 자리로 대신한다.
     */
    private static func caretPoint() -> CGPoint? {
        guard AXIsProcessTrusted(), Date() >= caretQuietUntil else { return nil }
        let started = Date()
        let point = askCaretPoint()
        // 대답이 느린 앱이 있다. 초당 30발을 쏘면서 발마다 그걸 기다리면 줄이 밀린다.
        // 한 번 느렸으면 잠깐은 묻지 않고 마우스 자리로 쏜다.
        if Date().timeIntervalSince(started) > 0.04 { caretQuietUntil = Date().addingTimeInterval(2) }
        return point
    }
    private static var caretQuietUntil = Date.distantPast

    private static func askCaretPoint() -> CGPoint? {
        let system = AXUIElementCreateSystemWide()
        // 받는 앱이 멈춰 있으면 대답이 안 온다. 총이 그걸 기다리며 같이 멈추면 안 된다.
        AXUIElementSetMessagingTimeout(system, 0.12)

        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement

        var value: CFTypeRef?
        var range = CFRange()
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXValueGetTypeID(),
              AXValueGetValue(value as! AXValue, .cfRange, &range) else { return nil }

        // 글을 골라 둔 채로 쏘면 그 글이 바뀐다. 고른 글의 첫머리가 과녁이다.
        if range.length > 0 {
            return textBounds(element, range.location, range.length).map { CGPoint(x: $0.minX, y: $0.midY) }
        }

        // **빈 범위의 네모를 그대로 믿지 않는다.** 텍스트 편집기는 그걸 실제보다 한 줄 위로
        // 알려 준다(그 자리 글자의 네모는 y=135 인데 빈 범위는 122 — 재 봤다). 글자의 네모는
        // 정확하므로 바로 뒤 글자, 없으면 바로 앞 글자에서 자리를 얻는다.
        if let next = textBounds(element, range.location, 1) {
            return CGPoint(x: next.minX, y: next.midY)
        }
        if range.location > 0, let prev = textBounds(element, range.location - 1, 1) {
            // 앞 글자가 줄바꿈이면 그 네모는 윗줄 끝에 있다. 커서는 그 아랫줄 맨 앞이다.
            if textString(element, range.location - 1, 1) == "\n" {
                let lineStart = textBounds(element, range.location, 0)?.minX ?? prev.minX
                return CGPoint(x: lineStart, y: prev.midY + prev.height)
            }
            return CGPoint(x: prev.maxX, y: prev.midY)
        }

        // 글자가 하나도 없다(빈 칸). 빈 범위의 네모밖에 없는데, 그게 칸 위로 삐져나와 있으면
        // 위의 그 어긋남이므로 한 줄 내린다.
        guard var rect = textBounds(element, range.location, 0) else { return nil }
        if let top = elementTop(element), rect.midY < top { rect.origin.y += rect.height }
        return CGPoint(x: rect.minX, y: rect.midY)
    }

    /// 글의 한 구간이 화면에서 차지하는 네모. 답이 없거나 말이 안 되면 nil.
    private static func textBounds(_ element: AXUIElement, _ location: Int, _ length: Int) -> CGRect? {
        var range = CFRange(location: location, length: length)
        var out: CFTypeRef?
        var rect = CGRect.zero
        guard let value = AXValueCreate(.cfRange, &range),
              AXUIElementCopyParameterizedAttributeValue(
                element, kAXBoundsForRangeParameterizedAttribute as CFString, value, &out) == .success,
              let out, CFGetTypeID(out) == AXValueGetTypeID(),
              AXValueGetValue(out as! AXValue, .cgRect, &rect),
              rect.height > 1, rect.origin.x.isFinite, rect.origin.y.isFinite else { return nil }
        return rect
    }

    private static func textString(_ element: AXUIElement, _ location: Int, _ length: Int) -> String? {
        var range = CFRange(location: location, length: length)
        var out: CFTypeRef?
        guard let value = AXValueCreate(.cfRange, &range),
              AXUIElementCopyParameterizedAttributeValue(
                element, kAXStringForRangeParameterizedAttribute as CFString, value, &out) == .success
        else { return nil }
        return out as? String
    }

    /// 글 칸의 윗변(화면 좌표).
    private static func elementTop(_ element: AXUIElement) -> CGFloat? {
        var out: CFTypeRef?
        var point = CGPoint.zero
        guard AXUIElementCopyAttributeValue(element, kAXPositionAttribute as CFString, &out) == .success,
              let out, CFGetTypeID(out) == AXValueGetTypeID(),
              AXValueGetValue(out as! AXValue, .cgPoint, &point) else { return nil }
        return point.y
    }

    /// 붙여넣는 자리를 렌더러에 알린다 — 총이 거기로 와서 쏜다. 글자 커서를 모르면 마우스 자리다.
    private func showShot(at caret: CGPoint?, text: String) {
        let frame = window.frame
        var x: CGFloat, y: CGFloat
        if let caret {
            // 손쉬운 사용 좌표는 주 화면 왼쪽 위가 원점이고, 창 좌표(Cocoa)는 왼쪽 아래가 원점이다.
            let top = Self.primaryScreen.frame.height - frame.maxY
            x = caret.x - frame.minX
            y = caret.y - top
        } else {
            let mouse = NSEvent.mouseLocation
            x = mouse.x - frame.minX
            y = frame.maxY - mouse.y
        }
        debugLog("과녁 \(caret == nil ? "마우스" : "글자 커서") \(Int(x)),\(Int(y))")
        call("__gunShotAt", Double(x), Double(y), text)
    }

    /**
     방아쇠 단축키의 ⌥·⇧·⌃ 에서 손이 떨어질 때까지 기다린다.

     안 기다리면 받는 앱이 ⌘V 가 아니라 **⌘⌥⇧V** 를 받을 수 있다 — 많은 앱에서 그건
     「서식 없이 붙여넣기」이거나 아예 다른 명령이다. 누르고 있는지 **읽기만** 하는 것이라
     아무것도 삼키지 않는다.

     **⌘ 는 안 기다린다.** 기본 방아쇠가 ⌘V 라, ⌘ 를 누른 채 V 만 여러 번 두드리는 것이
     보통의 손버릇이다. 우리가 보내는 키는 수식키를 직접 적어 넣으므로(쳐 넣는 글자는
     「아무것도 안 눌림」, 붙여넣기는 「⌘ 만」) 손이 ⌘ 위에 있어도 그대로 들어간다 —
     텍스트 편집기에 ⌘ 를 누른 채로 쏴서 확인했다.
     */
    private func waitForModifiersUp() {
        let held: CGEventFlags = [.maskAlternate, .maskShift, .maskControl]
        let deadline = Date().addingTimeInterval(modifierWait)
        while Date() < deadline,
              !CGEventSource.flagsState(.combinedSessionState).intersection(held).isEmpty {
            usleep(10_000)
        }
    }

    /// 글자를 직접 쳐 넣는다. 키코드가 아니라 **글자 자체**를 실어 보내므로 자판 배열과도,
    /// 한/영 상태와도 상관없이 그 글자가 들어간다. 클립보드를 건드리지 않는다.
    private static func type(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let units = Array(text.utf16)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down)
            event?.flags = []
            event?.setIntegerValueField(.eventSourceUserData, value: KeyTap.mark)
            event?.keyboardSetUnicodeString(stringLength: units.count, unicodeString: units)
            event?.post(tap: .cghidEventTap)
        }
    }

    /// 키 하나를 눌렀다 뗀다. flags 를 직접 적어 넣으므로 지금 눌린 수식키와 섞이지 않는다.
    private static func tap(key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = flags
            // 우리 탭이 이걸 「사람이 누른 단축키」로 다시 잡지 않게 표시해 둔다.
            event?.setIntegerValueField(.eventSourceUserData, value: KeyTap.mark)
            event?.post(tap: .cghidEventTap)
        }
    }

